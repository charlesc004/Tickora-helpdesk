using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
using Tickora.Domain;

namespace Tickora.Infrastructure.Persistence;

public sealed class ApplicationUser : IdentityUser
{
    public string DisplayName { get; set; } = "";
    public bool Active { get; set; } = true;
}

public sealed class ApplicationDbContext(DbContextOptions<ApplicationDbContext> options) : IdentityDbContext<ApplicationUser>(options)
{
    public DbSet<Ticket> Tickets => Set<Ticket>();
    public DbSet<SupportQueue> Queues => Set<SupportQueue>();
    public DbSet<TicketCategory> Categories => Set<TicketCategory>();
    public DbSet<QueueMembership> Memberships => Set<QueueMembership>();
    public DbSet<SlaPolicy> SlaPolicies => Set<SlaPolicy>();
    public DbSet<Notification> Notifications => Set<Notification>();
    public DbSet<KnowledgeArticle> Articles => Set<KnowledgeArticle>();
    public DbSet<CustomerFeedback> Feedback => Set<CustomerFeedback>();
    public DbSet<CannedResponse> Responses => Set<CannedResponse>();
    protected override void OnModelCreating(ModelBuilder b)
    {
        base.OnModelCreating(b);
        // Child IDs are generated by the domain. This lets EF discover appended children as Added,
        // rather than treating an already-populated generated key as an existing database row.
        b.Entity<Ticket>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<TicketMessage>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<TicketActivity>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<SlaPause>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<TicketAttachment>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<SupportQueue>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<TicketCategory>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<Notification>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<KnowledgeArticle>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<CannedResponse>().Property(x => x.Id).ValueGeneratedNever();
        b.Entity<ApplicationUser>().Property(x => x.DisplayName).HasMaxLength(120);
        b.Entity<Ticket>(e =>
        {
            e.HasKey(x => x.Id); e.Property(x => x.Number).UseIdentityColumn(1001); e.HasIndex(x => x.Number).IsUnique();
            e.HasIndex(x => new { x.CustomerId, x.SubmissionId }).IsUnique();
            e.HasIndex(x => new { x.QueueId, x.Status, x.UpdatedAt }); e.HasIndex(x => x.AssignedAgentId);
            e.HasIndex(x => new { x.Status, x.ResolutionDue }); e.HasIndex(x => x.FirstResponseDue);
            e.Property(x => x.Subject).HasMaxLength(180); e.Property(x => x.Description).HasMaxLength(10000);
            e.Property(x => x.RowVersion).IsRowVersion();
            e.HasOne<ApplicationUser>().WithMany().HasForeignKey(x => x.CustomerId).OnDelete(DeleteBehavior.Restrict);
            e.HasOne<ApplicationUser>().WithMany().HasForeignKey(x => x.AssignedAgentId).OnDelete(DeleteBehavior.Restrict);
            e.HasOne<SupportQueue>().WithMany().HasForeignKey(x => x.QueueId).OnDelete(DeleteBehavior.Restrict);
            e.HasOne<TicketCategory>().WithMany().HasForeignKey(x => x.CategoryId).OnDelete(DeleteBehavior.Restrict);
            e.HasMany(x => x.Messages).WithOne().HasForeignKey(x => x.TicketId).OnDelete(DeleteBehavior.Restrict);
            e.HasMany(x => x.Activities).WithOne().HasForeignKey(x => x.TicketId).OnDelete(DeleteBehavior.Restrict);
            e.HasMany(x => x.Pauses).WithOne().HasForeignKey(x => x.TicketId).OnDelete(DeleteBehavior.Restrict);
            e.HasMany(x => x.Attachments).WithOne().HasForeignKey(x => x.TicketId).OnDelete(DeleteBehavior.Restrict);
        });
        b.Entity<TicketMessage>(e =>
        {
            e.Property(x => x.Body).HasMaxLength(10000); e.Property(x => x.AuthorName).HasMaxLength(120);
            e.HasIndex(x => new { x.TicketId, x.AuthorId, x.SubmissionId }).IsUnique();
            e.HasOne<ApplicationUser>().WithMany().HasForeignKey(x => x.AuthorId).OnDelete(DeleteBehavior.Restrict);
        });
        b.Entity<TicketActivity>(e =>
        {
            e.Property(x => x.Description).HasMaxLength(300); e.HasIndex(x => new { x.TicketId, x.CreatedAt });
            e.Property(x => x.EventKey).HasMaxLength(180);
            e.HasIndex(x => new { x.TicketId, x.EventKey }).IsUnique().HasFilter("[EventKey] IS NOT NULL");
        });
        b.Entity<TicketAttachment>(e => { e.Property(x => x.FileName).HasMaxLength(180); e.Property(x => x.StorageKey).HasMaxLength(64); e.Property(x => x.ContentType).HasMaxLength(100); });
        b.Entity<SupportQueue>(e => { e.Property(x => x.Name).HasMaxLength(100); e.HasIndex(x => x.Name).IsUnique(); e.Property(x => x.RowVersion).IsRowVersion(); });
        b.Entity<TicketCategory>(e => { e.Property(x => x.Name).HasMaxLength(100); e.HasIndex(x => x.Name).IsUnique(); e.Property(x => x.RowVersion).IsRowVersion(); });
        b.Entity<QueueMembership>(e =>
        {
            e.HasKey(x => new { x.QueueId, x.AgentId });
            e.HasOne<SupportQueue>().WithMany().HasForeignKey(x => x.QueueId).OnDelete(DeleteBehavior.Restrict);
            e.HasOne<ApplicationUser>().WithMany().HasForeignKey(x => x.AgentId).OnDelete(DeleteBehavior.Restrict);
        });
        b.Entity<SlaPolicy>(e => { e.HasKey(x => x.Priority); e.Property(x => x.RowVersion).IsRowVersion(); });
        b.Entity<Notification>(e =>
        {
            e.Property(x => x.EventKey).HasMaxLength(180); e.Property(x => x.Title).HasMaxLength(180);
            e.HasIndex(x => new { x.RecipientId, x.EventKey }).IsUnique(); e.HasIndex(x => new { x.RecipientId, x.CreatedAt });
            e.HasOne<ApplicationUser>().WithMany().HasForeignKey(x => x.RecipientId).OnDelete(DeleteBehavior.Restrict);
            e.HasOne<Ticket>().WithMany().HasForeignKey(x => x.TicketId).OnDelete(DeleteBehavior.Restrict);
        });
        b.Entity<KnowledgeArticle>(e =>
        {
            e.Property(x => x.Slug).HasMaxLength(180); e.HasIndex(x => x.Slug).IsUnique();
            e.Property(x => x.Title).HasMaxLength(180); e.Property(x => x.Summary).HasMaxLength(400);
            e.Property(x => x.Category).HasMaxLength(100); e.Property(x => x.Body).HasMaxLength(30000);
            e.Property(x => x.RowVersion).IsRowVersion();
            e.HasOne<ApplicationUser>().WithMany().HasForeignKey(x => x.AuthorId).OnDelete(DeleteBehavior.Restrict);
        });
        b.Entity<CustomerFeedback>(e =>
        {
            e.HasKey(x => x.TicketId); e.Property(x => x.Comment).HasMaxLength(1000);
            e.HasOne<Ticket>().WithOne().HasForeignKey<CustomerFeedback>(x => x.TicketId).OnDelete(DeleteBehavior.Restrict);
            e.ToTable(t => t.HasCheckConstraint("CK_Feedback_Rating", "[Rating] BETWEEN 1 AND 5"));
        });
        b.Entity<CannedResponse>(e => { e.Property(x => x.Title).HasMaxLength(120); e.Property(x => x.Body).HasMaxLength(10000); e.Property(x => x.RowVersion).IsRowVersion(); });
    }
}
